    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String user = usuario.getText() != null ? usuario.getText().trim() : "";
        String pass = new String(contrasenia.getPassword());

        if (user.isEmpty() || pass.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor ingrese el usuario y la contraseña.",
                    "Campos Vacíos",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            AppControlador control = new AppControlador();
            String token = control.login(user, pass);

            if (token != null && !token.isBlank()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "¡Bienvenido " + user + "!\nInicio de sesión exitoso.",
                        "Login Exitoso",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE);

                ConversorView vistaPrincipal = new ConversorView();
                vistaPrincipal.setLocationRelativeTo(null);
                vistaPrincipal.setVisible(true);

                this.dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Usuario o contraseña incorrectos.",
                        "Error de Autenticación",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception ex) {
            String mensaje = ex.getMessage();
            if (mensaje == null || mensaje.isBlank()) {
                mensaje = "Usuario/Contraseña incorrectas o error de conexión con el servidor.";
            }
            javax.swing.JOptionPane.showMessageDialog(this,
                    mensaje,
                    "Error de Autenticación",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

