    private void btnConvertirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConvertirActionPerformed
        try { 
            String txtValor = valor.getText() != null ? valor.getText().trim() : "";
            if (txtValor.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese un valor a convertir.");
                return;
            }

            double num = Double.parseDouble(txtValor);
            String unidadInicial = (String) undInit.getSelectedItem();
            String unidadFinal = (String) undFinal.getSelectedItem();
            String tipo = (String) cmbMagnitud.getSelectedItem();

            AppControlador control = new AppControlador();
            double conversion;

            if ("MASA".equalsIgnoreCase(tipo)) {
                conversion = control.convertirMasa(num, unidadInicial, unidadFinal);
            } else if ("TEMPERATURA".equalsIgnoreCase(tipo)) {
                conversion = control.convertirTemperatura(num, unidadInicial, unidadFinal);
            } else {
                conversion = control.convertirLongitud(num, unidadInicial, unidadFinal);
            }

            conversionResultado.setText(String.valueOf(conversion));
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un número válido.");
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al convertir: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnConvertirActionPerformed

