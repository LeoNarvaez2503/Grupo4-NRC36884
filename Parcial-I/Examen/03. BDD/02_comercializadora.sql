CREATE DATABASE IF NOT EXISTS comercializadora_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE comercializadora_db;

DROP TABLE IF EXISTS FACTURA_DETALLE;
DROP TABLE IF EXISTS FACTURA;
DROP TABLE IF EXISTS TELEFONO_CELULAR;

-- 1. Catalogo de Telefonos Celulares (Sin inventario de stock fisico, solo entidad catalogo)
CREATE TABLE TELEFONO_CELULAR (
    COD_TELEFONO INT NOT NULL AUTO_INCREMENT,
    MARCA VARCHAR(50) NOT NULL,
    MODELO VARCHAR(100) NOT NULL,
    PRECIO NUMERIC(10,2) NOT NULL,
    CARACTERISTICAS TEXT NOT NULL,
    IMAGEN_URL VARCHAR(255) NULL,
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    PRIMARY KEY (COD_TELEFONO)
) ENGINE=InnoDB;

-- 2. Usuarios del Sistema (Autenticacion Centralizada)
CREATE TABLE IF NOT EXISTS USUARIO (
    COD_USUARIO INT NOT NULL AUTO_INCREMENT,
    USUARIO VARCHAR(50) NOT NULL UNIQUE,
    CLAVE VARCHAR(255) NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    ROL VARCHAR(50) NOT NULL DEFAULT 'ADMINISTRADOR',
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (COD_USUARIO)
) ENGINE=InnoDB;

-- 3. Facturacion de Ventas (CABECERA). Una factura puede tener VARIOS items (carrito),
--    cuyo detalle vive en FACTURA_DETALLE. Efectivo con 42% desc. o Credito Directo BanQuito.
--    Las columnas COD_TELEFONO / MODELO_TELEFONO / PRECIO_UNITARIO quedan como resumen
--    informativo (compatibilidad con clientes anteriores); la fuente de verdad es el detalle.
CREATE TABLE FACTURA (
    NUM_FACTURA INT NOT NULL AUTO_INCREMENT,
    NUMERO_COMPROBANTE VARCHAR(50) NOT NULL UNIQUE,
    FECHA TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    COD_CLIENTE_BANCO INT NULL,
    CEDULA_CLIENTE VARCHAR(20) NOT NULL,
    NOMBRE_CLIENTE VARCHAR(100) NOT NULL,
    COD_TELEFONO INT NULL,
    MODELO_TELEFONO VARCHAR(255) NULL,
    PRECIO_UNITARIO NUMERIC(10,2) NULL,
    SUBTOTAL NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    FORMA_PAGO VARCHAR(20) NOT NULL,
    PORCENTAJE_DESCUENTO NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    VALOR_DESCUENTO NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    TOTAL_PAGAR NUMERIC(10,2) NOT NULL,
    COD_CREDITO_BANCO INT NULL,
    NUM_CUOTAS INT NULL,
    VALOR_CUOTA NUMERIC(10,2) NULL,
    OBSERVACION VARCHAR(255) NULL,
    PRIMARY KEY (NUM_FACTURA)
) ENGINE=InnoDB;

-- 4. Detalle de Factura (un renglon por telefono del carrito)
CREATE TABLE FACTURA_DETALLE (
    COD_DETALLE INT NOT NULL AUTO_INCREMENT,
    NUM_FACTURA INT NOT NULL,
    COD_TELEFONO INT NOT NULL,
    MODELO_TELEFONO VARCHAR(160) NOT NULL,
    PRECIO_UNITARIO NUMERIC(10,2) NOT NULL,
    CANTIDAD INT NOT NULL DEFAULT 1,
    SUBTOTAL NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (COD_DETALLE),
    CONSTRAINT FK_DETALLE_FACTURA FOREIGN KEY (NUM_FACTURA)
        REFERENCES FACTURA (NUM_FACTURA) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_DETALLE_TELEFONO FOREIGN KEY (COD_TELEFONO)
        REFERENCES TELEFONO_CELULAR (COD_TELEFONO) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0)
) ENGINE=InnoDB;

