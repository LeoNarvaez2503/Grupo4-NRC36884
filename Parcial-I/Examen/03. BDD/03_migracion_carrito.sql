USE comercializadora_db;

CREATE TABLE IF NOT EXISTS FACTURA_DETALLE (
    COD_DETALLE INT NOT NULL AUTO_INCREMENT,
    NUM_FACTURA INT NOT NULL,
    COD_TELEFONO INT NOT NULL,
    MODELO_TELEFONO VARCHAR(160) NOT NULL,
    PRECIO_UNITARIO NUMERIC(10,2) NOT NULL,
    CANTIDAD INT NOT NULL DEFAULT 1,
    SUBTOTAL NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (COD_DETALLE),
    CONSTRAINT FK_DETALLE_FACTURA FOREIGN KEY (NUM_FACTURA)
        REFERENCES FACTURA (NUM_FACTURA) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_DETALLE_TELEFONO FOREIGN KEY (COD_TELEFONO)
        REFERENCES TELEFONO_CELULAR (COD_TELEFONO) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0)
) ENGINE=InnoDB;

ALTER TABLE FACTURA ADD COLUMN SUBTOTAL NUMERIC(10,2) NOT NULL DEFAULT 0.00 AFTER PRECIO_UNITARIO;
ALTER TABLE FACTURA DROP FOREIGN KEY FK_FACTURA_TELEFONO;
ALTER TABLE FACTURA MODIFY COD_TELEFONO INT NULL,
                    MODIFY MODELO_TELEFONO VARCHAR(255) NULL,
                    MODIFY PRECIO_UNITARIO NUMERIC(10,2) NULL;

-- Las facturas antiguas pasan a tener un renglon de detalle (cantidad 1)
INSERT INTO FACTURA_DETALLE (NUM_FACTURA, COD_TELEFONO, MODELO_TELEFONO, PRECIO_UNITARIO, CANTIDAD, SUBTOTAL)
SELECT F.NUM_FACTURA, F.COD_TELEFONO, F.MODELO_TELEFONO, F.PRECIO_UNITARIO, 1, F.PRECIO_UNITARIO
  FROM FACTURA F
 WHERE F.COD_TELEFONO IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM FACTURA_DETALLE D WHERE D.NUM_FACTURA = F.NUM_FACTURA);
UPDATE FACTURA SET SUBTOTAL = PRECIO_UNITARIO WHERE SUBTOTAL = 0 AND PRECIO_UNITARIO IS NOT NULL;
