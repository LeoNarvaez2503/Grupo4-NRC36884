CREATE DATABASE IF NOT EXISTS banquito_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE banquito_db;

-- 1. Eliminacion previa de tablas para regeneracion limpia
DROP TABLE IF EXISTS TABLA_AMORTIZACION;
DROP TABLE IF EXISTS CREDITO;
DROP TABLE IF EXISTS MOVIMIENTO;
DROP TABLE IF EXISTS CUENTA;
DROP TABLE IF EXISTS CLIENTE;

-- 2. Creacion de Entidades CORE del Banco
CREATE TABLE CLIENTE (
    COD_CLIENTE INT NOT NULL AUTO_INCREMENT,
    CEDULA VARCHAR(100) NOT NULL UNIQUE,
    NOMBRE VARCHAR(100) NOT NULL,
    GENERO VARCHAR(1) NOT NULL,
    FECHA_NACIMIENTO DATE NOT NULL,
    PRIMARY KEY (COD_CLIENTE)
) ENGINE=InnoDB;

CREATE TABLE CUENTA (
    NUM_CUENTA VARCHAR(8) NOT NULL,
    COD_CLIENTE INT NOT NULL,
    SALDO NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    PRIMARY KEY (NUM_CUENTA),
    CONSTRAINT FK_CUENTA_CLIENTE FOREIGN KEY (COD_CLIENTE) 
        REFERENCES CLIENTE (COD_CLIENTE) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE MOVIMIENTO (
    COD_MOVIMIENTO INT NOT NULL AUTO_INCREMENT,
    NUM_CUENTA VARCHAR(8) NOT NULL,
    TIPO VARCHAR(3) NOT NULL,
    VALOR NUMERIC(10,2) NOT NULL,
    FECHA DATE NOT NULL,
    PRIMARY KEY (COD_MOVIMIENTO),
    CONSTRAINT FK_MOVIMIENTO_CUENTA FOREIGN KEY (NUM_CUENTA) 
        REFERENCES CUENTA (NUM_CUENTA) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

-- 3. Entidades del Modulo de Credito
CREATE TABLE CREDITO (
    COD_CREDITO INT NOT NULL AUTO_INCREMENT,
    COD_CLIENTE INT NOT NULL,
    MONTO NUMERIC(10,2) NOT NULL,
    NUM_CUOTAS INT NOT NULL,
    TASA_INTERES_ANUAL NUMERIC(5,2) NOT NULL DEFAULT 16.50,
    VALOR_CUOTA NUMERIC(10,2) NOT NULL,
    FECHA_CREACION TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    PRIMARY KEY (COD_CREDITO),
    CONSTRAINT FK_CREDITO_CLIENTE FOREIGN KEY (COD_CLIENTE) 
        REFERENCES CLIENTE (COD_CLIENTE) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE TABLA_AMORTIZACION (
    COD_AMORTIZACION INT NOT NULL AUTO_INCREMENT,
    COD_CREDITO INT NOT NULL,
    NUM_CUOTA INT NOT NULL,
    VALOR_CUOTA NUMERIC(10,2) NOT NULL,
    INTERES_PAGADO NUMERIC(10,2) NOT NULL,
    CAPITAL_PAGADO NUMERIC(10,2) NOT NULL,
    SALDO NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (COD_AMORTIZACION),
    CONSTRAINT FK_AMORTIZACION_CREDITO FOREIGN KEY (COD_CREDITO) 
        REFERENCES CREDITO (COD_CREDITO) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

